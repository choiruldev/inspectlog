/**
 * HAR (HTTP Archive) 1.2 Generator
 * Converts captured Playwright requests into standard HAR 1.2 format.
 * Compatible with Chrome DevTools, Charles Proxy, Postman, and Fiddler.
 */

function getByteLength(str: string): number {
  if (typeof TextEncoder !== "undefined") {
    return new TextEncoder().encode(str).length;
  }
  if (typeof Buffer !== "undefined") {
    return Buffer.byteLength(str, "utf8");
  }
  return str.length;
}

export function convertRequestsToHAR(meta: {
  targetUrl: string;
  finalUrl?: string;
  pageTitle?: string;
  navigationTimeMs?: number;
}, requests: any[]): object {
  const startedDateTime = new Date().toISOString();

  const entries = (requests || []).map((req, index) => {
    const entryStart = new Date(req.timestamp || Date.now()).toISOString();
    const duration = req.durationMs || 50;

    // Format request headers
    const reqHeaders = Object.entries(req.requestHeaders || {}).map(([name, value]) => ({
      name,
      value: String(value),
    }));

    // Format response headers
    const resHeaders = Object.entries(req.responseHeaders || {}).map(([name, value]) => ({
      name,
      value: String(value),
    }));

    // Query string array
    const queryString = Object.entries(req.queryParams || {}).map(([name, value]) => ({
      name,
      value: String(value),
    }));

    // Format request body (postData)
    let postData: any = undefined;
    if (req.requestPayload) {
      const text =
        typeof req.requestPayload === "string"
          ? req.requestPayload
          : JSON.stringify(req.requestPayload, null, 2);
      postData = {
        mimeType: req.requestHeaders?.["content-type"] || "application/json",
        text,
      };
    }

    // Format response content
    let responseText = "";
    if (req.responseBody) {
      responseText =
        typeof req.responseBody === "string"
          ? req.responseBody
          : JSON.stringify(req.responseBody, null, 2);
    }

    const responseMime = req.responseHeaders?.["content-type"] || "application/json";

    return {
      startedDateTime: entryStart,
      time: duration,
      request: {
        method: req.method || "GET",
        url: req.url,
        httpVersion: "HTTP/1.1",
        cookies: [],
        headers: reqHeaders,
        queryString,
        headersSize: -1,
        bodySize: postData ? getByteLength(postData.text || "") : 0,
        ...(postData ? { postData } : {}),
      },
      response: {
        status: req.status || (req.failed ? 0 : 200),
        statusText: req.statusText || (req.failed ? "Failed" : "OK"),
        httpVersion: "HTTP/1.1",
        cookies: [],
        headers: resHeaders,
        content: {
          size: getByteLength(responseText),
          mimeType: responseMime,
          text: responseText,
        },
        redirectURL: "",
        headersSize: -1,
        bodySize: getByteLength(responseText),
      },
      cache: {},
      timings: {
        blocked: 0,
        dns: -1,
        connect: -1,
        send: 1,
        wait: Math.max(1, duration - 5),
        receive: 4,
        ssl: -1,
      },
      serverIPAddress: "",
      connection: String(index + 1),
    };
  });

  return {
    log: {
      version: "1.2",
      creator: {
        name: "InspectLog",
        version: "1.0.0",
        comment: "Generated by InspectLog Web & API Runtime Inspector",
      },
      browser: {
        name: "Headless Chrome / Playwright",
        version: "124.0.0",
      },
      pages: [
        {
          startedDateTime,
          id: "page_1",
          title: meta.pageTitle || meta.targetUrl,
          pageTimings: {
            onContentLoad: meta.navigationTimeMs || 1000,
            onLoad: meta.navigationTimeMs || 1500,
          },
        },
      ],
      entries,
    },
  };
}

export function downloadHARFile(filename: string, harObj: object) {
  const jsonString = JSON.stringify(harObj, null, 2);
  const blob = new Blob([jsonString], { type: "application/json" });
  const downloadUrl = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = downloadUrl;
  a.download = filename.endsWith(".har") ? filename : `${filename}.har`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(downloadUrl);
}
